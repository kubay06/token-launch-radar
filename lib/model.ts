// Token Launch Radar — model radar-2.
//
// One sealed snapshot in, one ranked board out. The board ranks only protocols
// that record no token yet, and it keeps the live-token protocols in a separate
// view with their market caps, never mixed into the ranking.
//
// Implied value is derived from the snapshot's own figures, never from a
// hand-kept list of names. The same function scores every protocol:
//
//   peer     = median market-cap / TVL of the live-token protocols in the
//              same category (at least 3 peers), else the global median
//              across all live-token protocols; clamped to [0.08, 0.60].
//              A category whose live peers trade richly earns a richer
//              multiple; a thin category earns the market average.
//   growth   = 1 + clamp(change_7d, -50, 100) / 100 * 0.6
//   maturity = 0.70 + min(age_days, 1095) / 1095 * 0.50
//              (age unknown: 365 days). A protocol that has run a long
//              time with no token has more pent-up launch value.
//   chains   = 1 + 0.04 * min(chains - 1, 5), at least 1.
//   implied  = round(tvl_usd * peer * growth * maturity * chains)
//
// Eligibility mirrors the watchlist's own rule, applied to every row, not
// just the watchlist: pre-token, not a bridge / liquid-staking / restaking /
// CEX product, not a versioned pool, and no wrapped / staked / staking word
// in the name. The watchlist is the floor: all 40 of its slugs are always
// in, and the early radar adds every other eligible protocol below the
// floor, by the same rule — 158 of them in this snapshot, 198 rows total.

/** One protocol entry: exactly the ten fields the sealed input carries. */
export interface SnapshotProtocol {
  slug: string;
  name: string;
  category: string | null;
  chains: string[];
  tvl_usd: number;
  change_7d: number | null;
  mcap_usd: number | null;
  listed_at: string | null;
  gecko_id: string | null;
  symbol: string | null;
}

/** The whole snapshot document. */
export interface Snapshot {
  as_of: string;
  source: string;
  floor_usd: number;
  protocols: SnapshotProtocol[];
  watchlist: string[];
}

